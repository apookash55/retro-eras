package dev.retroeras.player;

import java.util.Map;
import java.util.UUID;
import java.util.concurrent.ConcurrentHashMap;

import org.jspecify.annotations.Nullable;

import dev.retroeras.Era;
import dev.retroeras.RetroEras;

import net.fabricmc.fabric.api.entity.event.v1.ServerEntityLevelChangeEvents;
import net.fabricmc.fabric.api.entity.event.v1.ServerLivingEntityEvents;
import net.fabricmc.fabric.api.event.lifecycle.v1.ServerTickEvents;
import net.fabricmc.fabric.api.networking.v1.PayloadTypeRegistry;
import net.fabricmc.fabric.api.networking.v1.ServerPlayNetworking;

import net.minecraft.advancements.AdvancementHolder;
import net.minecraft.core.BlockPos;
import net.minecraft.network.RegistryFriendlyByteBuf;
import net.minecraft.network.codec.StreamCodec;
import net.minecraft.network.protocol.common.custom.CustomPacketPayload;
import net.minecraft.resources.Identifier;
import net.minecraft.server.MinecraftServer;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.tags.DamageTypeTags;
import net.minecraft.tags.ItemTags;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.animal.pig.Pig;
import net.minecraft.world.entity.monster.Enemy;
import net.minecraft.world.entity.monster.Ghast;
import net.minecraft.world.entity.monster.skeleton.Skeleton;
import net.minecraft.world.entity.projectile.arrow.AbstractArrow;
import net.minecraft.world.entity.projectile.hurtingprojectile.LargeFireball;
import net.minecraft.world.entity.vehicle.minecart.AbstractMinecart;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.Items;

/**
 * The achievements of Beta 1.7.3 and 1.6.4, the two eras that had them, kept apart from 26.3's advancements and from
 * each other (see PlayerAdvancementsMixin). They live under data/retroeras/advancement/&lt;era&gt;/, generated by
 * tools/gen_achievements.js, and are awarded here at the moments the old game awarded them: picking up wood, taking a
 * crafted pickaxe out of the crafting grid, smelting iron, and so on. As then, an achievement can only be earned once the
 * one before it has been ("Requires ..."). Alpha, Infdev, Classic and Cave game had no achievements, so nothing is
 * earned there.
 */
public final class EraAchievements {
	/** Sent by the client when it opens the inventory, which the server cannot otherwise see; "Taking Inventory". */
	public record OpenedInventory() implements CustomPacketPayload {
		public static final Type<OpenedInventory> TYPE = new Type<>(RetroEras.id("opened_inventory"));
		public static final StreamCodec<RegistryFriendlyByteBuf, OpenedInventory> CODEC = StreamCodec.unit(new OpenedInventory());

		@Override
		public Type<? extends CustomPacketPayload> type() {
			return TYPE;
		}
	}

	/** Where each player got into the minecart they are riding, for "On A Rail". */
	private static final Map<UUID, BlockPos> MINECART_STARTS = new ConcurrentHashMap<>();

	private EraAchievements() {
	}

	/** The era whose achievements live under {@code id}, or null for 26.3's own advancements. */
	public static @Nullable Era owner(Identifier id) {
		if (!id.getNamespace().equals(RetroEras.MOD_ID)) {
			return null;
		}
		int slash = id.getPath().indexOf('/');
		String era = slash < 0 ? id.getPath() : id.getPath().substring(0, slash);
		for (Era candidate : Era.values()) {
			if (candidate.getName().equals(era)) {
				return candidate;
			}
		}
		return null;
	}

	/** Whether the player may earn advancement {@code id} where they are: the era's own in that era, 26.3's outside. */
	public static boolean mayEarn(ServerPlayer player, Identifier id) {
		return owner(id) == Era.fromDimension(player.level().dimension());
	}

	/** Awards the era achievement {@code name} if the player is in an era that had it and has earned its parent. */
	public static void award(ServerPlayer player, String name) {
		Era era = Era.fromDimension(player.level().dimension());
		MinecraftServer server = player.level().getServer();
		if (era == null || server == null) {
			return;
		}
		AdvancementHolder achievement = server.getAdvancements().get(RetroEras.id(era.getName() + "/" + name));
		if (achievement == null) {
			return;
		}
		Identifier parent = achievement.value().parent().orElse(null);
		if (parent != null) {
			AdvancementHolder parentHolder = server.getAdvancements().get(parent);
			if (parentHolder != null && !player.getAdvancements().getOrStartProgress(parentHolder).isDone()) {
				return;
			}
		}
		player.getAdvancements().award(achievement, "achieved");
	}

	public static void init() {
		PayloadTypeRegistry.serverboundPlay().register(OpenedInventory.TYPE, OpenedInventory.CODEC);
		ServerPlayNetworking.registerGlobalReceiver(OpenedInventory.TYPE, (payload, context) -> award(context.player(), "open_inventory"));

		ServerLivingEntityEvents.AFTER_DEATH.register((entity, source) -> {
			if (!(source.getEntity() instanceof ServerPlayer player)) {
				return;
			}
			if (entity instanceof Enemy) {
				award(player, "kill_enemy");
			}
			// A skeleton shot dead from 50 blocks away, measured flat.
			if (entity instanceof Skeleton && source.getDirectEntity() instanceof AbstractArrow) {
				double dx = player.getX() - entity.getX();
				double dz = player.getZ() - entity.getZ();
				if (dx * dx + dz * dz >= 2500.0) {
					award(player, "snipe_skeleton");
				}
			}
			if (entity instanceof Ghast && source.getDirectEntity() instanceof LargeFireball) {
				award(player, "ghast");
			}
		});

		ServerLivingEntityEvents.ALLOW_DAMAGE.register((entity, source, amount) -> {
			// Eight hearts in one blow of your own.
			if (source.getEntity() instanceof ServerPlayer player && source.getDirectEntity() == player && amount >= 18.0F) {
				award(player, "overkill");
			}
			// A pig falling more than five blocks with you on it.
			if (entity instanceof Pig pig && source.is(DamageTypeTags.IS_FALL) && pig.fallDistance > 5.0 && pig.getFirstPassenger() instanceof ServerPlayer player) {
				award(player, "fly_pig");
			}
			return true;
		});

		ServerEntityLevelChangeEvents.AFTER_PLAYER_CHANGE_LEVEL.register((player, origin, destination) -> {
			Era era = Era.fromDimension(destination.dimension());
			if (era != null && era.isNether(destination.dimension())) {
				award(player, "portal");
			}
		});

		ServerTickEvents.END_SERVER_TICK.register(server -> {
			for (ServerPlayer player : server.getPlayerList().getPlayers()) {
				onARail(player);
			}
		});
	}

	/** Travel by minecart at least 1 km from where you got in. */
	private static void onARail(ServerPlayer player) {
		Entity vehicle = player.getVehicle();
		if (!(vehicle instanceof AbstractMinecart) || Era.fromDimension(player.level().dimension()) == null) {
			MINECART_STARTS.remove(player.getUUID());
			return;
		}
		BlockPos start = MINECART_STARTS.computeIfAbsent(player.getUUID(), uuid -> player.blockPosition());
		if (start.distSqr(player.blockPosition()) >= 1000000.0) {
			award(player, "on_a_rail");
		}
	}

	/** An item picked up off the ground: wood, leather, diamonds and blaze rods. */
	public static void onPickup(ServerPlayer player, ItemStack stack) {
		if (stack.is(ItemTags.LOGS)) {
			award(player, "mine_wood");
		} else if (stack.is(Items.LEATHER)) {
			award(player, "kill_cow");
		} else if (stack.is(Items.DIAMOND)) {
			award(player, "diamonds");
		} else if (stack.is(Items.BLAZE_ROD)) {
			award(player, "blaze_rod");
		}
	}

	/** An item taken out of a crafting grid. */
	public static void onCraft(ServerPlayer player, ItemStack stack) {
		if (stack.is(Items.CRAFTING_TABLE)) {
			award(player, "build_work_bench");
		} else if (stack.is(Items.WOODEN_PICKAXE)) {
			award(player, "build_pickaxe");
		} else if (stack.is(Items.FURNACE)) {
			award(player, "build_furnace");
		} else if (stack.is(Items.WOODEN_HOE)) {
			award(player, "build_hoe");
		} else if (stack.is(Items.BREAD)) {
			award(player, "make_bread");
		} else if (stack.is(Items.CAKE)) {
			award(player, "bake_cake");
		} else if (stack.is(Items.STONE_PICKAXE)) {
			award(player, "build_better_pickaxe");
		} else if (stack.is(Items.WOODEN_SWORD)) {
			award(player, "build_sword");
		} else if (stack.is(Items.ENCHANTING_TABLE)) {
			award(player, "enchantments");
		} else if (stack.is(Items.BOOKSHELF)) {
			award(player, "bookcase");
		}
	}

	/** An item taken out of a furnace. */
	public static void onSmelt(ServerPlayer player, ItemStack stack) {
		if (stack.is(Items.IRON_INGOT)) {
			award(player, "acquire_iron");
		} else if (stack.is(Items.COOKED_COD)) {
			award(player, "cook_fish");
		}
	}
}
