param(
  [string]$Jar = (Join-Path $env:APPDATA '.minecraft\versions\a1.2.6\a1.2.6.jar'),
  [string]$Out = (Join-Path $PSScriptRoot '..\src\client\resources\assets\retroeras\era_textures\alpha.json')
)
# Builds the Alpha 1.2.6 texture mapping from Beta's. Alpha's terrain.png and items.png use the same layout, but the
# slots Beta later filled (sandstone, lapis, wool colours, beds, cake, repeaters...) hold a placeholder grid or nothing
# in Alpha, so those tiles are left out. Alpha's redstone dust sits at different tiles and has its colour drawn in, so
# its bright (powered) tiles are turned grey for 26.3 to tint. Needs the player's own Alpha jar to look at the tiles;
# nothing from it is copied into the mod.
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
Add-Type -AssemblyName System.IO.Compression.FileSystem

function Read-Atlas($zip, $name) {
  $stream = $zip.GetEntry($name).Open()
  try { return [Drawing.Bitmap]::new($stream) } finally { $stream.Dispose() }
}
function Tile-Pixels($bitmap, $tile) {
  $x0 = ($tile % 16) * 16; $y0 = [math]::Floor($tile / 16) * 16
  $pixels = New-Object int[] 256
  for ($y = 0; $y -lt 16; $y++) { for ($x = 0; $x -lt 16; $x++) { $pixels[$y * 16 + $x] = $bitmap.GetPixel($x0 + $x, $y0 + $y).ToArgb() } }
  return ,$pixels
}

$zip = [IO.Compression.ZipFile]::OpenRead($Jar)
try {
  $terrain = Read-Atlas $zip 'terrain.png'
  $items = Read-Atlas $zip 'gui/items.png'
  $entries = @($zip.Entries | ForEach-Object { $_.FullName })
} finally { $zip.Dispose() }

# Tile 200 is the placeholder grid in Alpha (two shades of lavender); any tile identical to it is unused.
$placeholder = Tile-Pixels $terrain 200
$skipTerrain = @()
for ($t = 0; $t -lt 256; $t++) {
  $p = Tile-Pixels $terrain $t
  if ([Linq.Enumerable]::SequenceEqual([int[]]$p, [int[]]$placeholder)) { $skipTerrain += $t }
}
$skipItems = @()
for ($t = 0; $t -lt 256; $t++) {
  $p = Tile-Pixels $items $t
  if (-not ($p | Where-Object { ($_ -shr 24) -band 0xFF })) { $skipItems += $t }
}

$beta = Join-Path $PSScriptRoot '..\src\client\resources\assets\retroeras\era_textures\beta.json'
$script = @'
const fs = require('fs');
const [betaPath, outPath, skipTerrain, skipItems, entriesPath] = process.argv.slice(2);
const inJar = new Set(JSON.parse(fs.readFileSync(entriesPath, 'utf8')));
const skip = { 'terrain.png': new Set(JSON.parse(skipTerrain)), 'gui/items.png': new Set(JSON.parse(skipItems)) };
const map = JSON.parse(fs.readFileSync(betaPath, 'utf8'));
map._comment = 'Generated by tools/gen_alpha_texture_map.ps1 from beta.json and the player\'s own Alpha 1.2.6 jar; edit that script instead. '
  + 'Same layout as Beta, minus the tiles Alpha did not have yet. Alpha\'s redstone dust is red already, so its powered tiles are turned grey for 26.3 to tint.';
map.jar = 'a1.2.6';
// Slots that held something else in Alpha: no cobweb yet (11); its iron, gold and diamond blocks had their own side and
// bottom textures (38-40, 54-56) where Beta later put the grass overlay, tall grass, dead bush and fern; and its redstone
// dust (84) where Beta has the trapdoor.
const alphaOnly = new Set([11, 38, 39, 40, 54, 55, 56, 84]);
for (const id of alphaOnly) skip['terrain.png'].add(id);
// Alpha's grass side had the green drawn in, with no overlay to tint.
map.clear = [...new Set([...(map.clear || []), 'block/grass_block_side_overlay'])];
for (const atlas of map.atlases) {
  const unused = skip[atlas.file] || new Set();
  for (const key of Object.keys(atlas.tiles)) {
    const targets = atlas.tiles[key];
    const redstone = targets.some(t => t.startsWith('block/redstone_dust'));
    if (unused.has(Number(key)) || redstone) delete atlas.tiles[key];
  }
  if (atlas.file === 'terrain.png') {
    atlas.tiles['101'] = ['block/redstone_dust_line0|rot90|grey', 'block/redstone_dust_line1|rot90|grey'];
  }
}
// Files Beta added (wolves, squid, the dispenser screen) are not in Alpha's jar.
map.files = map.files.filter(f => inJar.has(f.from));
map.regions = map.regions.filter(r => inJar.has(r.from));
// Composed textures whose tiles Alpha lacks (beds are tiles; the redstone dot comes from Alpha's own cross).
map.compose = map.compose.filter(c => c.parts.every(p => !('tile' in p) || !skip['terrain.png'].has(p.tile)) || c.to[0].includes('redstone_dust_dot'));
for (const c of map.compose) {
  if (c.to[0].startsWith('block/redstone_dust_dot')) {
    c.to = ['block/redstone_dust_dot|grey'];
    c._comment = "Alpha's powered redstone cross (tile 100), turned grey.";
    c.parts = [{ tile: 100, src: [4, 4, 8, 8], dst: [4, 4] }];
  }
}
fs.writeFileSync(outPath, JSON.stringify(map, null, 2) + '\n');
console.log(`Wrote ${outPath}`);
'@
$tmp = Join-Path ([IO.Path]::GetTempPath()) 'gen_alpha_texture_map.js'
Set-Content -Encoding utf8NoBOM $tmp $script
$entriesFile = Join-Path ([IO.Path]::GetTempPath()) 'alpha_jar_entries.json'
Set-Content -Encoding utf8NoBOM $entriesFile (ConvertTo-Json -Compress $entries)
node $tmp (Resolve-Path $beta) ([IO.Path]::GetFullPath($Out)) (ConvertTo-Json -Compress @($skipTerrain)) (ConvertTo-Json -Compress @($skipItems)) $entriesFile
Remove-Item $tmp, $entriesFile
Write-Host "Left out $($skipTerrain.Count) unused terrain tiles and $($skipItems.Count) empty item tiles"
